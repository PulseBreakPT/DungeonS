/* No packages required. Run with: node tests/smoke.cjs */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const E=require('../engine.js');
const S=E.create();
assert.equal(E.N,36);
assert.equal(S.grid.length,1296);
assert.equal(E.validate(S),true);
assert.equal(E.validate({version:1,grid:[]}),false);
assert.equal(S.name,'Nova Aurora');
let a=E.analyze(S);
assert.ok(a.population>=100,'Starter city needs inhabitants');
assert.ok(a.jobs>0,'Starter city needs employment');
assert.ok(a.powerCap>a.electricity,'Starter power must be sufficient');
assert.ok(a.waterCap>a.waterUse,'Starter water must be sufficient');
assert.ok(a.happiness>55,'Starter city should be healthy');
assert.ok(a.balance>=0,'Starter budget should be sustainable');
const before=S.money;
let r=E.build(S,5,5,'road');
assert.equal(r.ok,true);
assert.equal(S.money,before-E.COST.road);
assert.equal(E.build(S,5,5,'res').ok,false,'Cannot overwrite existing buildings');
assert.equal(E.build(S,-1,2,'road').ok,false,'No out-of-bounds placement');
const waterIndex=S.grid.findIndex(c=>c.t==='water');
assert.ok(waterIndex>=0);
assert.equal(E.build(S,waterIndex%E.N,Math.floor(waterIndex/E.N),'road').ok,false,'No construction on water');
assert.equal(E.build(S,5,5,'bulldoze').ok,true);
assert.equal(S.grid[E.idx(5,5)].k,'empty');
assert.equal(E.build(S,5,5,'res').ok,true);
assert.equal(S.grid[E.idx(5,5)].lvl,0);
const firstDate=E.date(S),firstMonth=S.month,firstYear=S.year;
const preMoney=S.money,profit=E.analyze(S).balance;
E.tick(S);
assert.equal(S.month,firstMonth+1);
assert.equal(S.year,firstYear);
assert.equal(S.money,preMoney+E.analyze(S).balance,'Monthly economy should apply');
const cloned=JSON.parse(JSON.stringify(S));
assert.equal(E.validate(cloned),true);
assert.deepEqual(E.analyze(cloned).population,E.analyze(S).population);
const src=fs.readFileSync(path.join(__dirname,'../game.js'),'utf8');
const html=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8');
for(const id of ['world','cityName','money','population','date','resBar','powerText','toolsPanel','modal','toast','importFile'])assert.ok(html.includes(`id="${id}"`),`Missing UI ${id}`);
assert.ok(html.includes('./engine.js')&&html.includes('./game.js'));
assert.ok(src.includes('addEventListener')&&src.includes('pointerdown')&&src.includes('localStorage'));
console.log('PASS: city initialization, zoning, roads, water, power, budget, simulation, save and responsive UI wiring.');